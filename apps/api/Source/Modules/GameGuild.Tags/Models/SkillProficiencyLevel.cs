namespace GameGuild.Tags;

/// <summary>
/// Represents the proficiency level for a skill tag.
/// </summary>
public enum SkillProficiencyLevel
{
    /// <summary>No prior experience.</summary>
    Beginner = 0,

    /// <summary>Basic understanding.</summary>
    Elementary = 1,

    /// <summary>Can work with some supervision.</summary>
    Intermediate = 2,

    /// <summary>Can work independently.</summary>
    Advanced = 3,

    /// <summary>Deep expertise.</summary>
    Expert = 4,

    /// <summary>Recognized authority in the field.</summary>
    Master = 5,
}
